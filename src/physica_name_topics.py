STOP = set('в на с из по от и а но или для при к о об как что это его ее их был были быть также при помощи метод результат работа исследование показано получен составляет однако может можно между через более менее чем году год годах который являться свойство структура образец'.split())

def top_words(texts, n=15):
    c=Counter()
    for t in texts:
        for w in re.findall(r'[А-ЯЁа-яё]{4,}', t.lower()):
            if w in STOP: continue
            try: nf=ma.parse(w)[0].normal_form
            except: nf=w
            if len(nf)>=4 and nf not in STOP: c[nf]+=1
    return [w for w,_ in c.most_common(n)]

