"""Фильтрация и анализ собранных карточек РНФ.

Оставляет только сверхпроводящие/квантовые проекты по маркерам в
названии/аннотации/ключевых словах/классификаторе. Считает статистику.
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

from utils import PROJECT_ROOT

# маркеры «сверхпроводящего» проекта (в нижнем регистре, по подстрокам)
SUPERCOND_MARKERS = [
    "сверхпровод",        # сверхпроводимость, сверхпроводник, сверхпроводящий
    "джозефсон",          # джозефсоновский, джозефсоновские
    "втсп",               # высокотемпературные сверхпроводники
    "сквид",              # СКВИД
    "куперовск",          # куперовские пары
    "кубит",              # кубиты, сверхпроводниковые кубиты
    "майоран",            # майорановские фермионы
    "спин-триплет",       # спин-триплетная сверхпроводимость
    "пиннинг",            # пиннинг вихрей
    "криоэлектроник",     # сверхпроводниковая криоэлектроника
    "болометр",           # сверхпроводниковые болометры
    "терагерц",           # терагерцовые генераторы (часто джозефсоновские)
]
# классификаторы РНФ, относящиеся к сверхпроводимости
SUPERCOND_CODES = ["02-209"]  # «Низкие температуры и сверхпроводимость»


def is_supercond(p: dict) -> bool:
    text = " ".join([
        str(p.get("title") or ""),
        str(p.get("Название") or ""),
        str(p.get("Аннотация") or ""),
        str(p.get("Ключевые слова") or ""),
        str(p.get("Область знания, основной код классификатора") or ""),
    ]).lower()
    for m in SUPERCOND_MARKERS:
        if m in text:
            return True
    return False


def main() -> None:
    inp = PROJECT_ROOT / "data/raw/rnf/rnf_cards.json"
    data = json.loads(inp.read_text(encoding="utf-8"))
    proj = data["projects"]
    print(f"всего карточек: {len(proj)}")

    sup = [p for p in proj if is_supercond(p)]
    print(f"сверхпроводящих/квантовых: {len(sup)} ({100*len(sup)//max(1,len(proj))}%)")

    # годы
    years = Counter()
    for p in sup:
        num = p.get("number", "")
        m = re.match(r"(\d{2})", num)
        if m:
            years["20" + m.group(1)] += 1
    print("\nпо годам:", dict(sorted(years.items())))

    # организации (топ)
    orgs = Counter()
    for p in sup:
        org = p.get("Организация финансирования, регион", "")
        # сократим до первой части
        short = re.split(r",\s*(?:г\.|Московск|Санкт|Новосибирск|Екатеринбург|Казан|Томск|Черноголовк|Долгопрудн|Нижний|Саратов|Иркутск|Красноярск|Владивосток|Тверь|Ярославль|Самара|Ростов|Пермь|Уфа|Омск|Тюмень|Челябинск|Калининград|Воронеж|Тула|Рязань|Оренбург|Барнаул|Тольятти|Курск|Брянск|Липецк|Астрахань|Ульяновск|Пенза|Кемерово|Волгоград|Набережные Челны|Сочи|Магнитогорск|Хабаровск|Якутск|Петрозаводск|Архангельск|Мурманск|Сургут|Нижневартовск|Норильск|Чита|Улан-Удэ|Грозный|Махачкала|Владикавказ|Нальчик|Черкесск|Майкоп|Элиста|Горно-Алтайск|Абакан|Кызыл|Биробиджан|Анадырь|Салехард|Ханты-Мансийск|Сыктывкар|Йошкар-Ола|Саранск|Чебоксары|Ижевск|Киров|Кострома|Вологда|Псков|Великий Новгород|Смоленск|Калуга|Тамбов|Орёл|Белгород|Тверь)", "", org)
        short = short.strip()
        orgs[short] += 1
    print("\nтоп организаций:")
    for o, c in orgs.most_common(12):
        print(f"  {c:3} | {o[:80]}")

    # классификаторы
    codes = Counter()
    for p in sup:
        code = p.get("Область знания, основной код классификатора", "")
        codes[code] += 1
    print("\nтоп классификаторов:")
    for c, n in codes.most_common(8):
        print(f"  {n:3} | {c[:90]}")

    # сохранение
    out = PROJECT_ROOT / "results/rnf_supercond_cards.json"
    out.write_text(json.dumps({"method": "rnf_supercond_filter", "n_total": len(proj),
                               "n_supercond": len(sup), "projects": sup},
                              ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nсохранено {len(sup)} проектов → {out}")


if __name__ == "__main__":
    sys.exit(main())
